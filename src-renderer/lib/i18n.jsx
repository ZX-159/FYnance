/* ------------------------- locale-aware formatting ------------------------- */

function fmtNumber(locale, v, opts) {
  try {
    return new Intl.NumberFormat(locale, opts).format(v);
  } catch {
    return String(v);
  }
}

export function fmtRM(locale, v) {
  if (v === null || v === undefined || v === '' || Number.isNaN(Number(v))) return '—';
  return fmtNumber(locale, Number(v), { style: 'currency', currency: 'MYR' });
}

export function fmtDate(locale, s) {
  if (!s) return '—';
  const d = new Date(s);
  if (Number.isNaN(d.getTime())) return s;
  try {
    return d.toLocaleDateString(locale, { day: '2-digit', month: 'short', year: 'numeric' });
  } catch {
    return s;
  }
}

export function fmtDateTime(locale, s) {
  if (!s) return 'never';
  const d = new Date(s);
  if (Number.isNaN(d.getTime())) return s;
  try {
    return d.toLocaleString(locale, { day: '2-digit', month: 'short', hour: '2-digit', minute: '2-digit' });
  } catch {
    return s;
  }
}

/* ------------------------------ i18n context ------------------------------ */

const I18nContext = createContext({ t: (k) => k, lang: 'en', locale: 'en-MY' });

export function I18nProvider({ language = 'en', children }) {
  const value = useMemo(() => {
    const lang = MESSAGES[language] ? language : 'en';
    const dict = MESSAGES[lang];
    const locale = LOCALES[lang] || 'en-MY';

    const t = (key, vars) => {
      let s = dict[key] ?? MESSAGES.en[key] ?? key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          s = s.split(`{${k}}`).join(String(v));
        }
      }
      return s;
    };

    const timeAgo = (iso) => {
      if (!iso) return t('never');
      const sec = Math.max(0, (Date.now() - new Date(iso).getTime()) / 1000);
      if (sec < 5) return t('just_now');
      if (sec < 60) return t('s_ago', { n: Math.floor(sec) });
      if (sec < 3600) return t('m_ago', { n: Math.floor(sec / 60) });
      if (sec < 86400) return t('h_ago', { n: Math.floor(sec / 3600) });
      return t('d_ago', { n: Math.floor(sec / 86400) });
    };

    return { t, lang, locale, timeAgo, fmtRM: (v) => fmtRM(locale, v), fmtDate: (s) => fmtDate(locale, s), fmtDateTime: (s) => fmtDateTime(locale, s) };
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
